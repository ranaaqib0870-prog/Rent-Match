create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.listings (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  owner_phone text not null,
  type text not null check (type in ('گھر','دکان')),
  area text not null,
  rent numeric(12,2) not null check (rent > 0),
  advance numeric(12,2) not null default 0 check (advance >= 0),
  size text,
  description text,
  photo_urls text[] not null default '{}',
  latitude double precision,
  longitude double precision,
  status text not null default 'active' check (status in ('active','removed')),
  created_at timestamptz not null default now(),
  constraint listing_latitude_range check (latitude is null or latitude between -90 and 90),
  constraint listing_longitude_range check (longitude is null or longitude between -180 and 180)
);

-- Ensure these columns are added even when the listings table already existed.
alter table public.listings
  add column if not exists latitude double precision,
  add column if not exists longitude double precision,
  add column if not exists photo_urls text[] not null default '{}',
  add column if not exists status text not null default 'active';

create index if not exists listings_status_created_idx on public.listings(status, created_at desc);
create index if not exists listings_area_idx on public.listings using gin (to_tsvector('simple', area));
create index if not exists listings_owner_idx on public.listings(owner_id);
create index if not exists listings_coordinates_idx on public.listings(latitude, longitude);

create table if not exists public.listing_reports (
  id bigint generated by default as identity primary key,
  listing_id bigint not null references public.listings(id) on delete cascade,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reason text not null,
  created_at timestamptz not null default now(),
  unique (listing_id, reporter_id)
);

create index if not exists listing_reports_listing_idx on public.listing_reports(listing_id);

-- Create a profile automatically for each new authenticated user.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email)
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert or update of email on auth.users
  for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.listings enable row level security;
alter table public.listing_reports enable row level security;

drop policy if exists "Users can read own profile and admins can read all" on public.profiles;
drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile"
on public.profiles for select to authenticated
using (id = (select auth.uid()));

drop policy if exists "Users can update own email only" on public.profiles;
create policy "Users can update own email only"
on public.profiles for update to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()) and role = 'user');

drop policy if exists "Anyone can read active listings" on public.listings;
create policy "Anyone can read active listings"
on public.listings for select
using (status = 'active' or exists (
  select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'
) or owner_id = (select auth.uid()));

drop policy if exists "Authenticated users can publish their own listings" on public.listings;
create policy "Authenticated users can publish their own listings"
on public.listings for insert to authenticated
with check (owner_id = (select auth.uid()) and status = 'active');

drop policy if exists "Owners and admins can update listings" on public.listings;
create policy "Owners and admins can update listings"
on public.listings for update to authenticated
using (owner_id = (select auth.uid()) or exists (
  select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'
))
with check (owner_id = (select auth.uid()) or exists (
  select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'
));

drop policy if exists "Owners and admins can delete listings" on public.listings;
create policy "Owners and admins can delete listings"
on public.listings for delete to authenticated
using (owner_id = (select auth.uid()) or exists (
  select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'
));

drop policy if exists "Users can submit reports as themselves" on public.listing_reports;
create policy "Users can submit reports as themselves"
on public.listing_reports for insert to authenticated
with check (reporter_id = (select auth.uid()));

drop policy if exists "Users can read own reports and admins can read all" on public.listing_reports;
create policy "Users can read own reports and admins can read all"
on public.listing_reports for select to authenticated
using (reporter_id = (select auth.uid()) or exists (
  select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'
));

-- Public photo bucket; upload is restricted to a user's own folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('listing-photos', 'listing-photos', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "Anyone can view listing photos" on storage.objects;
create policy "Anyone can view listing photos"
on storage.objects for select
using (bucket_id = 'listing-photos');

drop policy if exists "Authenticated users upload photos to own folder" on storage.objects;
create policy "Authenticated users upload photos to own folder"
on storage.objects for insert to authenticated
with check (bucket_id = 'listing-photos' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "Users can delete photos in own folder" on storage.objects;
create policy "Users can delete photos in own folder"
on storage.objects for delete to authenticated
using (bucket_id = 'listing-photos' and (storage.foldername(name))[1] = (select auth.uid())::text);

